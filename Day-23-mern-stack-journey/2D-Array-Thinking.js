// Better Thinking

// Step 1:
// Visualize rows and columns first

let arr = [
    [1,2,3],
    [4,5,6],
    [7,8,9]
];

// rows = 3
// columns = 3

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// Step 2:
// Decide loop responsibility

// Outer loop → rows
// Inner loop → columns

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){

        console.log(arr[i][j]);

    }
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// Step 3:
// Understand indexes clearly

// arr[0][0] → 1
// arr[1][2] → 6
// arr[2][1] → 8

console.log(arr[1][2]); // 6

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 1️. Print Row-wise

for(let i = 0; i < arr.length; i++){

    let row = "";

    for(let j = 0; j < arr[i].length; j++){
        row += arr[i][j] + " ";
    }

    console.log(row);
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 2️. Print Column-wise

for(let j = 0; j < arr[0].length; j++){

    let col = "";

    for(let i = 0; i < arr.length; i++){
        col += arr[i][j] + " ";
    }

    console.log(col);
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 3️. Visual Understanding

// [
//  [1,2,3],  → row 0
//  [4,5,6],  → row 1
//  [7,8,9]   → row 2
// ]

// arr[2][1]
// row = 2
// column = 1
// answer = 8

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// Common Mistakes

// 1. Using wrong loop inside
// 2. Mixing row and column
// 3. Accessing wrong indexes

