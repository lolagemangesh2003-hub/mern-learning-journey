// 2D Array Logic Practice

let arr = [
    [1,2,3],
    [4,5,6],
    [7,8,9]
];

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 1️. Print all elements row-wise

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){
        console.log(arr[i][j]);
    }
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 2️. Print all elements column-wise

for(let j = 0; j < arr[0].length; j++){

    for(let i = 0; i < arr.length; i++){
        console.log(arr[i][j]);
    }
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 3️. Print diagonal

for(let i = 0; i < arr.length; i++){
    console.log(arr[i][i]);
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 4️. Find sum of all elements

let sum = 0;

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){
        sum += arr[i][j];
    }
}

console.log(sum); // 45

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 5️. Count even numbers

let count = 0;

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){

        if(arr[i][j] % 2 === 0){
            count++;
        }
    }
}

console.log(count); // 4

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 6️. Find max element

let max = arr[0][0];

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){

        if(arr[i][j] > max){
            max = arr[i][j];
        }
    }
}

console.log(max); // 9

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 7️. Reverse rows

for(let i = arr.length - 1; i >= 0; i--){
    console.log(arr[i]);
}

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 8️. Flatten 2D array

let flat = [];

for(let i = 0; i < arr.length; i++){

    for(let j = 0; j < arr[i].length; j++){
        flat.push(arr[i][j]);
    }
}

console.log(flat);

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 9️. Search element

function search2D(arr, target){

    for(let i = 0; i < arr.length; i++){

        for(let j = 0; j < arr[i].length; j++){

            if(arr[i][j] === target){
                return [i, j];
            }
        }
    }

    return [-1, -1];
}

console.log(search2D(arr, 5)); // [1,1]

// ---------------------------------------------------------------------------------------------------------------------------------------------------------------------

// 10. Sum of each row

for(let i = 0; i < arr.length; i++){

    let rowSum = 0;

    for(let j = 0; j < arr[i].length; j++){
        rowSum += arr[i][j];
    }

    console.log(rowSum);
}

